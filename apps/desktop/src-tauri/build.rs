use tauri_build::{AppManifest, Attributes};

fn main() {
    println!("cargo:rerun-if-changed=capabilities");

    // The test-notification spike command only exists in debug builds (see
    // `lib.rs`), so its capability file is only loaded there. Release builds
    // only load `default.json`.
    let release = std::env::var("PROFILE").is_ok_and(|profile| profile == "release");
    let capabilities = if release {
        "./capabilities/default.json"
    } else {
        "./capabilities/*.json"
    };

    tauri_build::try_build(
        Attributes::new()
            .capabilities_path_pattern(capabilities)
            // Permissions are generated for all commands in every profile (stable
            // `permissions/autogenerated`); an unregistered command stays unreachable.
            .app_manifest(AppManifest::new().commands(&[
                "schedule_test_notification",
                "get_autostart",
                "set_autostart",
                "weather_forecast",
                "weather_geocode",
                "backup_list",
                "backup_create",
                "backup_open_folder",
                "backup_restore",
                "backup_export",
                "backup_pick_external",
                "backup_acknowledge",
                "config_export_save",
                "config_import_pick",
                "config_import_apply",
                "dashboard_delete",
                "time_validate",
                "time_expand",
                "reminder_list",
                "reminder_create",
                "reminder_update",
                "reminder_delete",
                "reminder_unseen_deliveries",
                "reminder_mark_seen",
                "session_list_running",
                "session_history",
                "session_start",
                "session_stop",
                "session_rename",
                "session_delete",
                "habit_list",
                "habit_create",
                "habit_update",
                "habit_set_archived",
                "habit_delete",
                "habit_checks",
                "habit_set_check",
                "setting_get",
                "setting_list",
                "setting_set",
                "setting_delete",
                "dashboard_list",
                "dashboard_get",
                "dashboard_create",
                "dashboard_ensure_default",
                "dashboard_update",
                "dashboard_update_theme",
                "dashboard_create_with_widgets",
                "widget_list",
                "widget_get",
                "widget_create",
                "widget_update_config",
                "widget_update_layout",
                "widget_find_first_of_type",
                "widget_delete",
                "note_get",
                "note_create",
                "note_update",
                "note_delete",
                "note_search",
                "shortcut_list",
                "shortcut_create",
                "shortcut_update",
                "shortcut_delete",
                "shortcut_reorder",
                "shortcut_search",
                "todo_list_for_widget",
                "todo_list_create",
                "todo_list_items",
                "todo_create",
                "todo_update",
                "todo_shift_repeat_due",
                "todo_set_completed",
                "todo_delete",
                "todo_due",
                "todo_overdue",
                "todo_repeating_due",
                "todo_reorder",
                "todo_clear_completed",
                "todo_search",
            ])),
    )
    .expect("failed to run tauri-build");
}
