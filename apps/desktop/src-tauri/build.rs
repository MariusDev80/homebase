use tauri_build::{AppManifest, Attributes};

fn main() {
    println!("cargo:rerun-if-changed=capabilities");

    // The test-notification spike command only exists in debug builds (see
    // `lib.rs`), so its capability file is only loaded there. Release builds
    // only load `default.json`.
    let release = std::env::var("PROFILE").is_ok_and(|profile| profile == "release");
    let capabilities = if release {
        "./capabilities/default.json"
    } else {
        "./capabilities/*.json"
    };

    tauri_build::try_build(
        Attributes::new()
            .capabilities_path_pattern(capabilities)
            // Permissions are generated for all commands in every profile (stable
            // `permissions/autogenerated`); an unregistered command stays unreachable.
            .app_manifest(AppManifest::new().commands(&[
                "schedule_test_notification",
                "get_autostart",
                "set_autostart",
            ])),
    )
    .expect("failed to run tauri-build");
}
