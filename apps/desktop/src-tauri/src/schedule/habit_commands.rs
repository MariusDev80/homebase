/// D3: rewrites the exceptions of the habit's reminder so that they are the checked days of
/// `[J-1, J+1]` still to come, then recomputes the cache from `now`. `false` if the habit has no
/// reminder (or an unreadable one), or if nothing had to change. The caller holds the gate and
/// runs it inside the same transaction as the check or the habit write.
pub(crate) async fn sync_habit_reminder(
    conn: &mut SqliteConnection,
    habit_id: &str,
    now: Timestamp,
) -> Result<bool, ScheduleError> {
    let Some(row) = store::get_habit_reminder(conn, habit_id).await? else {
        return Ok(false);
    };
    let (Ok(tz), Ok(anchor)) = (
        parse_time_zone(&row.time_zone),
        parse_local_date_time(&row.start_local),
    ) else {
        // Written outside the Rust: reported as `invalid` by the list, left alone here.
        eprintln!("schedule: habit reminder {} is unreadable", row.id);
        return Ok(false);
    };
    let (from, to) = check_window(now, &tz);
    let days = habit_store::checked_days(
        conn,
        habit_id,
        &format_local_date(from),
        &format_local_date(to),
    )
    .await?;
    let checked: Vec<Date> = days
        .iter()
        .filter_map(|day| parse_local_date(day).ok())
        .collect();
    let Ok(wanted) = habit_exdates(&checked, anchor.time(), &tz, now) else {
        eprintln!("schedule: habit reminder {} is unreadable", row.id);
        return Ok(false);
    };
    let mut current = serde_json::from_str::<Vec<String>>(&row.exdates).ok();
    if let Some(list) = current.as_mut() {
        list.sort();
    }
    if current.as_ref() == Some(&wanted) {
        return Ok(false);
    }
    // A title, rule or zone the engine refuses (written outside the Rust) makes the reminder
    // unreadable: it is left alone and the check goes through (spec 4.8).
    let rebuilt = prepare(
        row.title.clone(),
        row.start_local.clone(),
        row.time_zone.clone(),
        row.rrule.clone(),
        wanted,
    )
    .and_then(|parts| {
        let cache = cache_for(&parts.spec, row.enabled, now)?;
        Ok((parts, cache))
    });
    let Ok((parts, cache)) = rebuilt else {
        eprintln!("schedule: habit reminder {} is unreadable", row.id);
        return Ok(false);
    };
    let changed = store::write_reminder_exdates(
        conn,
        &row.id,
        &parts.exdates_json,
        row.next_fire_at.as_deref(),
        cache_refs(&cache),
    )
    .await?;
    Ok(changed > 0)
}

/// Applies the reminder part of an input: none deletes the reminder, some creates or replaces
/// it (never enabled while the habit is archived), then derives its exceptions. `true` if a
/// reminder was written or deleted.
async fn write_habit_reminder(
    conn: &mut SqliteConnection,
    habit: &HabitRow,
    plan: Option<&ReminderPlan>,
    now: Timestamp,
) -> Result<bool, ScheduleError> {
    let Some(plan) = plan else {
        return store::delete_habit_reminder(conn, &habit.id).await;
    };
    let existing = store::get_habit_reminder(conn, &habit.id).await?;
    // The zone of an existing reminder is never changed by the form (as for the reminders).
    let time_zone = existing
        .as_ref()
        .map_or(plan.time_zone.as_str(), |row| row.time_zone.as_str());
    let parts = reminder_parts(&habit.title, time_zone, plan, existing.as_ref(), now)?;
    let enabled = plan.enabled && habit.archived_at.is_none();
    let cache = cache_for(&parts.spec, enabled, now)?;
    let stamp = format_instant(now);
    match existing {
        Some(old) => {
            let mut row = parts.into_row(old.id, enabled, cache, old.created_at, stamp);
            row.habit_id = Some(habit.id.clone());
            if !store::replace_habit_reminder(conn, &row).await? {
                return Err(ScheduleError::NotFound);
            }
        }
        None => {
            if store::count_reminders(conn).await? >= MAX_REMINDERS {
                return Err(ScheduleError::LimitReached);
            }
            let mut row = parts.into_row(plan.id.clone(), enabled, cache, stamp.clone(), stamp);
            row.habit_id = Some(habit.id.clone());
            store::insert_reminder(conn, &row).await?;
        }
    }
    sync_habit_reminder(conn, &habit.id, now).await?;
    Ok(true)
}

/// The habit and its reminder as stored, after a commit.
async fn load_dto(conn: &mut SqliteConnection, id: &str) -> Result<HabitDto, ScheduleError> {
    let habit = habit_store::get_habit(conn, id)
        .await?
        .ok_or(ScheduleError::NotFound)?;
    let reminder = store::get_habit_reminder(conn, id).await?.map(|row| {
        let cache = row.next_fire_at.clone().zip(row.next_fire_key.clone());
        let status = known_status(row.enabled, &cache);
        habit_reminder_dto(row, status)
    });
    Ok(habit_dto(habit, reminder))
}

