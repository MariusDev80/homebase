//! The seven Tauri commands of the habits (spec habits 4.3, lot H2). Every input comes from the
//! WebView: sizes, numbers and date ranges are bounded before any conversion, calculation or disk
//! access. Each command is a thin wrapper over a `pub(crate)` business function that takes the
//! [`SchedulerCtx`], so the logic is tested without Tauri. A command that touches a reminder takes
//! the gate, settles what is already due first (D12), writes in one transaction, shows its notices
//! outside the gate and wakes the scheduler thread after the commit.
//!
//! The SQL on `habits` and `habit_checks` is in `habit_store`, the SQL on `reminders` in `store`:
//! this file has none.

