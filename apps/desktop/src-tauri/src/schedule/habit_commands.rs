/// `{"kind":"days","days":["MO","WE"]}` or `{"kind":"weekly","target":3}`. The variants are
/// struct variants, so `deny_unknown_fields` applies to their fields too (S1, tested).
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum HabitScheduleDto {
    Days { days: Vec<String> },
    Weekly { target: u8 },
}

#[derive(serde::Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct HabitReminderInputDto {
    /// Id of a new reminder (generated by the front); ignored when the habit already has one.
    pub id: String,
    /// `HH:MM`.
    pub time: String,
    pub days: Vec<String>,
    pub time_zone: String,
    pub enabled: bool,
}

#[derive(serde::Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct HabitInputDto {
    pub title: String,
    pub schedule: HabitScheduleDto,
    pub start_on: String,
    /// Required: `null` removes the reminder, a missing key is an error (no accidental removal).
    #[serde(deserialize_with = "Option::deserialize")]
    pub reminder: Option<HabitReminderInputDto>,
}

#[derive(serde::Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct HabitCreateDto {
    pub id: String,
    pub title: String,
    pub schedule: HabitScheduleDto,
    pub start_on: String,
    pub reminder: Option<HabitReminderInputDto>,
}

#[derive(Debug, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct HabitReminderDto {
    pub reminder_id: String,
    pub time: String,
    pub days: Vec<&'static str>,
    pub time_zone: String,
    pub enabled: bool,
    pub next_fire_at: Option<String>,
    pub next_fire_key: Option<String>,
    pub status: ReminderStatus,
}

#[derive(Debug, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct HabitDto {
    pub id: String,
    pub title: String,
    pub schedule: HabitScheduleDto,
    pub start_on: String,
    pub archived_at: Option<String>,
    pub reminder: Option<HabitReminderDto>,
    pub created_at: String,
    pub updated_at: String,
}

#[derive(Debug, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct HabitCheckDto {
    pub habit_id: String,
    pub day_on: String,
}

fn schedule_dto(schedule: HabitSchedule) -> HabitScheduleDto {
    match schedule {
        HabitSchedule::Days { mask } => HabitScheduleDto::Days {
            days: days_of(mask).into_iter().map(str::to_owned).collect(),
        },
        HabitSchedule::Weekly { target } => HabitScheduleDto::Weekly { target },
    }
}

/// `HH:MM` of a stored anchor (`YYYY-MM-DDTHH:MM:SS`).
fn time_text(time: Time) -> String {
    format!("{:02}:{:02}", time.hour(), time.minute())
}

/// The reminder of a habit as the front sees it. A line whose anchor or rule left the two forms
/// (written outside the Rust) is reported with `status: invalid` and no days, never as an error.
fn habit_reminder_dto(row: ReminderRow, status: ReminderStatus) -> HabitReminderDto {
    let time = parse_local_date_time(&row.start_local).map(DateTime::time);
    let mask = row
        .rrule
        .as_deref()
        .and_then(|text| parse_rule(text, AnchorKind::DateTime).ok())
        .and_then(|rule| reminder_mask(&rule));
    let readable = time.is_ok() && mask.is_some();
    HabitReminderDto {
        reminder_id: row.id,
        time: time.map_or_else(|_| "00:00".to_owned(), time_text),
        days: mask.map(days_of).unwrap_or_default(),
        time_zone: row.time_zone,
        enabled: row.enabled,
        next_fire_at: row.next_fire_at,
        next_fire_key: row.next_fire_key,
        status: if readable {
            status
        } else {
            ReminderStatus::Invalid
        },
    }
}

fn habit_dto(row: HabitRow, reminder: Option<HabitReminderDto>) -> HabitDto {
    HabitDto {
        id: row.id,
        title: row.title,
        schedule: schedule_dto(row.schedule),
        start_on: row.start_on,
        archived_at: row.archived_at,
        reminder,
        created_at: row.created_at,
        updated_at: row.updated_at,
    }
}

