/// What the form asks for the reminder, once checked.
struct ReminderPlan {
    id: String,
    time: Time,
    mask: u8,
    time_zone: String,
    enabled: bool,
}

/// An input habit, once checked.
struct Valid {
    title: String,
    schedule: HabitSchedule,
    start_on: String,
    reminder: Option<ReminderPlan>,
}

/// Strict date of a user text, within the stored range (1900 to the latest allowed day).
fn parse_day(field: &str, text: &str, now: Timestamp) -> Result<Date, ScheduleError> {
    bounded(field, text, SHORT_TEXT_MAX)?;
    let day = parse_local_date(text).map_err(|_| ScheduleError::invalid(field))?;
    if day < jiff::civil::date(1900, 1, 1) || day > latest_allowed_day(now) {
        return Err(ScheduleError::invalid(field));
    }
    Ok(day)
}

fn schedule_of(dto: &HabitScheduleDto) -> Result<HabitSchedule, ScheduleError> {
    match dto {
        HabitScheduleDto::Days { days } => Ok(HabitSchedule::Days {
            mask: mask_of(days, "schedule.days")?,
        }),
        HabitScheduleDto::Weekly { target } => {
            if (1..=7).contains(target) {
                Ok(HabitSchedule::Weekly { target: *target })
            } else {
                Err(ScheduleError::invalid("schedule.target"))
            }
        }
    }
}

/// The checks of 4.3 in their order: title, schedule, start, then the reminder (time, days, time
/// zone and rule).
fn validate(
    title: String,
    schedule: &HabitScheduleDto,
    start_on: &str,
    reminder: Option<HabitReminderInputDto>,
    now: Timestamp,
) -> Result<Valid, ScheduleError> {
    bounded("title", &title, TITLE_MAX_CHARS)?;
    check_title(&title)?;
    let schedule = schedule_of(schedule)?;
    let start_on = format_local_date(parse_day("startOn", start_on, now)?);
    let reminder = reminder
        .map(|r| -> Result<ReminderPlan, ScheduleError> {
            let time = parse_time_of_day(&r.time)?;
            let mask = mask_of(&r.days, "reminder.days")?;
            bounded("reminder.timeZone", &r.time_zone, SHORT_TEXT_MAX)?;
            check_id(&r.id).map_err(|_| ScheduleError::invalid("reminder.id"))?;
            let plan = ReminderPlan {
                id: r.id,
                time,
                mask,
                time_zone: r.time_zone,
                enabled: r.enabled,
            };
            // Checks the zone and the rule the way a reminder is checked.
            reminder_parts(&title, &plan.time_zone, &plan, None, now)?;
            Ok(plan)
        })
        .transpose()?;
    Ok(Valid {
        title,
        schedule,
        start_on,
        reminder,
    })
}

/// The canonical reminder of a habit (D4): the habit's title, the rule of its days, the anchor
/// at `plan.time` today in `time_zone` (kept as is if the existing reminder has the same time).
/// No exceptions yet: [`sync_habit_reminder`] derives them.
fn reminder_parts(
    title: &str,
    time_zone: &str,
    plan: &ReminderPlan,
    existing: Option<&ReminderRow>,
    now: Timestamp,
) -> Result<Parts, ScheduleError> {
    let tz = parse_time_zone(time_zone).map_err(|_| ScheduleError::invalid("reminder.timeZone"))?;
    let today = tz.to_datetime(now).date();
    let fresh = format_local_date_time(DateTime::from_parts(today, plan.time));
    let start_local = match existing {
        Some(row)
            if row.time_zone == time_zone
                && parse_local_date_time(&row.start_local)
                    .is_ok_and(|anchor| anchor.time() == plan.time) =>
        {
            row.start_local.clone()
        }
        _ => fresh,
    };
    prepare(
        title.to_owned(),
        start_local,
        time_zone.to_owned(),
        Some(reminder_rule(plan.mask)),
        Vec::new(),
    )
}

fn cache_refs(cache: &Option<Cache>) -> Option<(&str, &str)> {
    cache.as_ref().map(|(at, key)| (at.as_str(), key.as_str()))
}

