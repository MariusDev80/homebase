pub(crate) async fn list_habits(ctx: &SchedulerCtx) -> Result<Vec<HabitDto>, ScheduleError> {
    let (habits, reminders, now) = locked!(ctx, conn => {
        let now = now_of(ctx)?;
        let habits = habit_store::list_habits(&mut conn).await?;
        let reminders = store::list_habit_reminders(&mut conn).await?;
        Ok((habits, reminders, now))
    })?;
    // Computing every status can be costly (it may search a rule): off the gate and off the
    // async worker threads.
    tauri::async_runtime::spawn_blocking(move || {
        let mut by_habit: HashMap<String, ReminderRow> = reminders
            .into_iter()
            .filter_map(|row| row.habit_id.clone().map(|owner| (owner, row)))
            .collect();
        habits
            .into_iter()
            .map(|habit| {
                let reminder = by_habit.remove(&habit.id).map(|row| {
                    let status = status_of(&row, now);
                    habit_reminder_dto(row, status)
                });
                habit_dto(habit, reminder)
            })
            .collect()
    })
    .await
    .map_err(|_| ScheduleError::Database)
}

pub(crate) async fn create_habit(
    ctx: &SchedulerCtx,
    input: HabitCreateDto,
) -> Result<HabitDto, ScheduleError> {
    let HabitCreateDto {
        id,
        title,
        schedule,
        start_on,
        reminder,
    } = input;
    check_id(&id)?;
    let valid = validate(title, &schedule, &start_on, reminder, now_of(ctx)?)?;
    let mut notices: Vec<Notice> = Vec::new();
    let result = locked!(ctx, conn => {
        let now = now_of(ctx)?;
        // A reminder is about to be written: what is already due is settled first.
        let settled = if valid.reminder.is_some() {
            settle(&mut conn, now, &mut notices).await?
        } else {
            false
        };
        let stamp = format_instant(now);
        let row = HabitRow {
            id: id.clone(),
            title: valid.title.clone(),
            schedule: valid.schedule,
            start_on: valid.start_on.clone(),
            archived_at: None,
            created_at: stamp.clone(),
            updated_at: stamp,
        };
        let mut tx = conn.begin_with("BEGIN IMMEDIATE").await?;
        // The insert comes first: an existing id is a `Conflict`, whatever the count; then the
        // count (new row included) is checked and the whole transaction is dropped if it is full.
        habit_store::insert_habit(&mut tx, &row).await?;
        if habit_store::count_habits(&mut tx).await? > MAX_HABITS {
            return Err(ScheduleError::LimitReached);
        }
        let touched = match valid.reminder.as_ref() {
            Some(plan) => write_habit_reminder(&mut tx, &row, Some(plan), now).await?,
            None => false,
        };
        tx.commit().await?;
        // Committed: the wake-up is owed even if the read-back fails.
        Ok((load_dto(&mut conn, &id).await, touched || settled))
    });
    show_notices(ctx, notices);
    let (dto, wake) = result?;
    if wake {
        ctx.signal.wake();
    }
    dto
}

pub(crate) async fn update_habit(
    ctx: &SchedulerCtx,
    id: String,
    input: HabitInputDto,
) -> Result<HabitDto, ScheduleError> {
    check_id(&id)?;
    let HabitInputDto {
        title,
        schedule,
        start_on,
        reminder,
    } = input;
    let valid = validate(title, &schedule, &start_on, reminder, now_of(ctx)?)?;
    let mut notices: Vec<Notice> = Vec::new();
    let result = locked!(ctx, conn => {
        let now = now_of(ctx)?;
        let settled = settle(&mut conn, now, &mut notices).await?;
        let existing = habit_store::get_habit(&mut conn, &id)
            .await?
            .ok_or(ScheduleError::NotFound)?;
        let row = HabitRow {
            id: id.clone(),
            title: valid.title.clone(),
            schedule: valid.schedule,
            start_on: valid.start_on.clone(),
            archived_at: existing.archived_at,
            created_at: existing.created_at,
            updated_at: format_instant(now),
        };
        let mut tx = conn.begin_with("BEGIN IMMEDIATE").await?;
        if !habit_store::replace_habit(&mut tx, &row).await? {
            return Err(ScheduleError::NotFound);
        }
        let touched = write_habit_reminder(&mut tx, &row, valid.reminder.as_ref(), now).await?;
        tx.commit().await?;
        // Committed: the wake-up is owed even if the read-back fails.
        Ok((load_dto(&mut conn, &id).await, touched || settled))
    });
    show_notices(ctx, notices);
    let (dto, wake) = result?;
    if wake {
        ctx.signal.wake();
    }
    dto
}

pub(crate) async fn set_habit_archived(
    ctx: &SchedulerCtx,
    id: String,
    archived: bool,
) -> Result<HabitDto, ScheduleError> {
    check_id(&id)?;
    let mut notices: Vec<Notice> = Vec::new();
    let result = locked!(ctx, conn => {
        let now = now_of(ctx)?;
        let settled = settle(&mut conn, now, &mut notices).await?;
        let before = habit_store::get_habit(&mut conn, &id)
            .await?
            .ok_or(ScheduleError::NotFound)?;
        let stamp = format_instant(now);
        let mut tx = conn.begin_with("BEGIN IMMEDIATE").await?;
        let archived_at = archived.then_some(stamp.as_str());
        if !habit_store::set_archived(&mut tx, &id, archived_at, &stamp).await? {
            return Err(ScheduleError::NotFound);
        }
        // Archiving silences the reminder; restoring leaves it disabled (H7).
        // Idempotent: an habit already archived has its reminder disabled already.
        let touched = if archived && before.archived_at.is_none() {
            store::disable_habit_reminder(&mut tx, &id, &stamp).await?
        } else {
            false
        };
        tx.commit().await?;
        // Committed: the wake-up is owed even if the read-back fails.
        Ok((load_dto(&mut conn, &id).await, touched || settled))
    });
    show_notices(ctx, notices);
    let (dto, wake) = result?;
    if wake {
        ctx.signal.wake();
    }
    dto
}

/// No `get_habit` first: a row too damaged to be read can still be deleted.
pub(crate) async fn delete_habit(ctx: &SchedulerCtx, id: String) -> Result<bool, ScheduleError> {
    check_id(&id)?;
    let mut notices: Vec<Notice> = Vec::new();
    let result = locked!(ctx, conn => {
        settle(&mut conn, now_of(ctx)?, &mut notices).await?;
        habit_store::delete_habit(&mut conn, &id).await
    });
    show_notices(ctx, notices);
    let deleted = result?;
    ctx.signal.wake();
    Ok(deleted)
}

pub(crate) async fn habit_checks_between(
    ctx: &SchedulerCtx,
    from: String,
    to: String,
) -> Result<Vec<HabitCheckDto>, ScheduleError> {
    let day = |field: &str, text: &str| -> Result<Date, ScheduleError> {
        bounded(field, text, SHORT_TEXT_MAX)?;
        parse_local_date(text).map_err(|_| ScheduleError::invalid(field))
    };
    let (from, to) = (day("from", &from)?, day("to", &to)?);
    if from > to {
        return Err(ScheduleError::invalid("to"));
    }
    let span = from
        .until(to)
        .map_err(|_| ScheduleError::invalid("to"))?
        .get_days();
    // `HABIT_RANGE_MAX_DAYS` days, bounds included.
    if i64::from(span) >= HABIT_RANGE_MAX_DAYS {
        return Err(ScheduleError::invalid("to"));
    }
    let (from, to) = (format_local_date(from), format_local_date(to));
    let rows = locked!(ctx, conn =>
        habit_store::checks_between(&mut conn, &from, &to, HABIT_CHECKS_MAX_ROWS).await
    )?;
    Ok(rows
        .into_iter()
        .map(|row| HabitCheckDto {
            habit_id: row.habit_id,
            day_on: row.day_on,
        })
        .collect())
}

/// Checks or unchecks a day; `true` if the stored state changed (idempotent). The check and the
/// derived exceptions of the reminder are one transaction.
pub(crate) async fn set_habit_check(
    ctx: &SchedulerCtx,
    habit_id: String,
    day_on: String,
    done: bool,
) -> Result<bool, ScheduleError> {
    check_id(&habit_id).map_err(|_| ScheduleError::invalid("habitId"))?;
    let day = format_local_date(parse_day("dayOn", &day_on, now_of(ctx)?)?);
    let mut notices: Vec<Notice> = Vec::new();
    let result = locked!(ctx, conn => {
        let now = now_of(ctx)?;
        // A reminder already due is delivered before the day is checked (L3).
        let settled = settle(&mut conn, now, &mut notices).await?;
        let habit = habit_store::get_habit(&mut conn, &habit_id)
            .await?
            .ok_or(ScheduleError::NotFound)?;
        if day < habit.start_on {
            return Err(ScheduleError::invalid("dayOn"));
        }
        let stamp = format_instant(now);
        let mut tx = conn.begin_with("BEGIN IMMEDIATE").await?;
        let changed = if done {
            habit_store::insert_check(&mut tx, &habit_id, &day, &stamp).await?
        } else {
            habit_store::delete_check(&mut tx, &habit_id, &day).await?
        };
        let touched = changed && sync_habit_reminder(&mut tx, &habit_id, now).await?;
        tx.commit().await?;
        Ok((changed, touched || settled))
    });
    show_notices(ctx, notices);
    let (changed, wake) = result?;
    if wake {
        ctx.signal.wake();
    }
    Ok(changed)
}

