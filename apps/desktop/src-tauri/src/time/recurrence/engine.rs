//! The ONLY file that imports the `rrule` crate and `chrono` (ADR-003 section 3.4, CA-B3).
//!
//! Floating expansion: the nominal wall-clock start is disguised as UTC so that the crate never
//! sees a daylight-saving change; resolving the wall-clock times to instants is done afterwards,
//! once, by `jiff` (`zone::resolve_local`). The rule is built from the validated structure and
//! never carries `UNTIL` (the caller filters on the resolved instant).

use super::{Freq, RecurrenceRule, RuleEnd, Weekday, MAX_ITERATIONS};
use crate::time::error::{RuleErrorCode, TimeError};
use chrono::{Datelike, TimeZone, Timelike};
use jiff::civil::DateTime;
use rrule::{Frequency, NWeekday, RRule, Tz};

fn frequency(freq: Freq) -> Frequency {
    match freq {
        Freq::Daily => Frequency::Daily,
        Freq::Weekly => Frequency::Weekly,
        Freq::Monthly => Frequency::Monthly,
        Freq::Yearly => Frequency::Yearly,
    }
}

fn weekday(day: Weekday) -> rrule::Weekday {
    match day {
        Weekday::Mo => rrule::Weekday::Mon,
        Weekday::Tu => rrule::Weekday::Tue,
        Weekday::We => rrule::Weekday::Wed,
        Weekday::Th => rrule::Weekday::Thu,
        Weekday::Fr => rrule::Weekday::Fri,
        Weekday::Sa => rrule::Weekday::Sat,
        Weekday::Su => rrule::Weekday::Sun,
    }
}

fn engine_failure() -> TimeError {
    TimeError::InvalidRule {
        code: RuleErrorCode::InvalidValue,
        part: None,
    }
}

fn to_floating(dt: DateTime) -> Option<chrono::DateTime<Tz>> {
    Tz::UTC
        .with_ymd_and_hms(
            i32::from(dt.year()),
            u32::try_from(dt.month()).ok()?,
            u32::try_from(dt.day()).ok()?,
            u32::try_from(dt.hour()).ok()?,
            u32::try_from(dt.minute()).ok()?,
            u32::try_from(dt.second()).ok()?,
        )
        .single()
}

fn from_floating(dt: &chrono::DateTime<Tz>) -> Option<DateTime> {
    DateTime::new(
        i16::try_from(dt.year()).ok()?,
        i8::try_from(dt.month()).ok()?,
        i8::try_from(dt.day()).ok()?,
        i8::try_from(dt.hour()).ok()?,
        i8::try_from(dt.minute()).ok()?,
        i8::try_from(dt.second()).ok()?,
        0,
    )
    .ok()
}

/// Nominal wall-clock times generated by the crate in "floating UTC", from the anchor `start`
/// (counted from there, so that `COUNT` and the `INTERVAL` alignment are right) up to `upper`
/// inclusive. `start` itself is included only when it matches the rule. More than
/// [`MAX_ITERATIONS`] candidates up to `upper` is an `ExpansionLimit` error.
pub(super) fn floating_occurrences(
    start: DateTime,
    rule: &RecurrenceRule,
    upper: DateTime,
) -> Result<Vec<DateTime>, TimeError> {
    let dt_start = to_floating(start).ok_or_else(engine_failure)?;
    let mut builder = RRule::new(frequency(rule.freq)).interval(rule.interval);
    if let RuleEnd::Count(count) = rule.end {
        builder = builder.count(count);
    }
    if !rule.by_day.is_empty() {
        builder = builder.by_weekday(
            rule.by_day
                .iter()
                .map(|day| NWeekday::Every(weekday(*day)))
                .collect(),
        );
    }
    if let Some((n, day)) = rule.by_nth_weekday {
        builder = builder.by_weekday(vec![NWeekday::Nth(i16::from(n), weekday(day))]);
    }
    if let Some(day) = rule.by_month_day {
        builder = builder.by_month_day(vec![day]);
    }
    let set = builder
        .build(dt_start)
        .map_err(|_| engine_failure())?
        .limit();

    // Invariant: the crate iterator is `limit()`ed, so after 100 000 loops without a result it
    // stops silently (`was_limited`, not observable through the public API) and looks like the end
    // of the series. Every rule of the supported subset yields within a few periods (worst case: a
    // 29 February yearly rule, 8 years; BYMONTHDAY=31 every 11 months, a few years), far below that
    // bound; `every_valid_rule_yields_an_occurrence_within_the_horizon` guards it.
    let mut occurrences = Vec::new();
    for (index, candidate) in set.into_iter().enumerate() {
        let nominal = from_floating(&candidate).ok_or(TimeError::ExpansionLimit)?;
        if nominal > upper {
            break;
        }
        if index >= MAX_ITERATIONS {
            return Err(TimeError::ExpansionLimit);
        }
        occurrences.push(nominal);
    }
    Ok(occurrences)
}
